#!/usr/bin/env python3
"""Write the incident review starter from the section list check-docs.py enforces.

docs/documentation/structure.md says incident reviews are begun from a template, and
check-docs.py fails a review that lacks a required section or skips one in order. Those
sections live in INCIDENT_SECTIONS there. A starter kept by hand beside that list would
go stale the first time a section was added, and nothing would notice, so this writes
the starter from the list itself and --check fails when the committed file differs.

The starter is a page to copy into docs/incidents/ and fill in. Everything a person must
fill in is the same marker, `<fill in>`, and check-docs.py fails any front-matter value
that still holds it. check-docs.py and build-llms-txt.js skip the starter itself, by its
exact path.

Every section needs a hint, and every hint a section. A section added to
INCIDENT_SECTIONS without one stops this script, so a starter never ships a heading with
no guidance under it, and a hint for a removed section can't linger.

Usage:
    python3 tools/build-incident-starter.py           rewrite the starter
    python3 tools/build-incident-starter.py --check   exit 1 if it is missing or stale
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECKER = ROOT / "tools" / "check-docs.py"

# One line on what goes under each required section, drawn from
# docs/documentation/incident-reviews.md. Keyed by the checker's own normalised heading.
HINTS = {
    "overview": "The executive summary, in paragraphs, then the revision history. "
                "It has to stand alone.",
    "impact and scope": "Who or what was affected, and how much. Time to detect and time "
                        "to act are separate measurements.",
    "timeline": "A table of timestamp, event and state (ok, warn or crit). Observations, "
                "not narration, in order, with a timezone.",
    "technical findings": "What was confirmed, each with its source. Mark an inference as "
                          "unproven and say what would settle it.",
    "root cause analysis": "The root cause, or the most likely cause labelled as "
                           "unconfirmed.",
    "resolution and recovery": "What restored service, and the current status: resolved, "
                               "mitigated or being watched.",
    "corrective and preventive actions": "A table of action, owner, due date and status. "
                                         "Each one traces to a finding above it.",
    "lessons learned": "Weak or missing signals, telemetry that would have cut time to "
                       "detect, and noisy or absent alerts. Each becomes a corrective action.",
    "monitoring plan": "What you'll watch to know the fix holds or the failure returns.",
    "open questions": "What's still unproven, and what would settle each question.",
    "appendix: evidence": "The logs, output and records the findings cite, each with its "
                          "source.",
    "appendix: investigation walkthrough": "The investigation in the order it happened, "
                                           "dead ends included.",
}

MARKER = "<fill in>"

# Every field check-docs.py requires of an incident page: title, type, status and updated
# for every page, then services, severity, window and data_loss. tests/test-check-docs.sh
# fills in a copy of the starter and expects it to pass, so a field the checker starts
# requiring fails there until it's added here. `window` is a mapping, which is how
# incident-reviews.md writes it. `type` is the one value that isn't left to the author.
FRONT_MATTER = f"""\
---
title: {MARKER}
type: incident
status: {MARKER}
updated: {MARKER}
services: [{MARKER}]
severity: {MARKER}
window:
  start: {MARKER}
  end: {MARKER}
data_loss: {MARKER}
---"""

NOTICE = (
    "<!-- Generated by tools/build-incident-starter.py from INCIDENT_SECTIONS in "
    "tools/check-docs.py. Edits to this file are lost on the next build. Copy it to "
    "docs/incidents/ as YYYY-MM-DD-slug.md, fill it in, and delete this comment. -->"
)


def load_checker():
    spec = importlib.util.spec_from_file_location("check_docs", CHECKER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def heading(section: str) -> str:
    """The checker lowercases a heading before comparing, so sentence case is accepted."""
    return section[:1].upper() + section[1:]


def render(sections: list[str]) -> str:
    # The marker sits in a code span in the body: markdownlint reads a bare <fill in> as
    # inline HTML (MD033). Front-matter values aren't linted as Markdown.
    body = [f"# `{MARKER}`"]
    for section in sections:
        body += [f"## {heading(section)}", f"_{HINTS[section]}_", f"`{MARKER}`"]
    return FRONT_MATTER + "\n\n" + NOTICE + "\n\n" + "\n\n".join(body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="fail if the starter is missing or differs from what would be written")
    args = parser.parse_args()

    checker = load_checker()
    sections = list(checker.INCIDENT_SECTIONS)
    unhinted = [s for s in sections if s not in HINTS]
    stale = [h for h in HINTS if h not in sections]
    if unhinted or stale:
        for s in unhinted:
            print(f"error: INCIDENT_SECTIONS has '{s}', and HINTS in {Path(__file__).name} "
                  "has no hint for it", file=sys.stderr)
        for h in stale:
            print(f"error: HINTS in {Path(__file__).name} has '{h}', which is not in "
                  "INCIDENT_SECTIONS", file=sys.stderr)
        return 2

    target: Path = checker.STARTER
    shown = target.relative_to(ROOT).as_posix()
    # Bytes, so a line-ending change counts as a difference and the file is written the
    # same on every platform.
    content = render(sections).encode("utf-8")

    if args.check:
        if not target.is_file():
            print(f"error: {shown} is missing.\n"
                  f"Run: python3 tools/{Path(__file__).name}", file=sys.stderr)
            return 1
        if target.read_bytes() != content:
            print(f"error: {shown} differs from what INCIDENT_SECTIONS and HINTS "
                  f"produce.\nRun: python3 tools/{Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{shown} matches INCIDENT_SECTIONS ({len(sections)} sections)")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content)
    print(f"wrote {shown} — {len(sections)} sections")
    return 0


if __name__ == "__main__":
    sys.exit(main())
